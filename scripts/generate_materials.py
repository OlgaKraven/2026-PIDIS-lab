def generate_reports() -> None:
    digest = hashlib.sha256(REFERENCE.read_bytes()).hexdigest().upper()
    if digest != REFERENCE_SHA256:
        raise RuntimeError(f"Reference DOCX changed: {digest}")
    reports = ROOT / "reports"
    reports.mkdir(parents=True, exist_ok=True)
    for lab in LABS:
        target = reports / f"{lab.id.replace('-', '_')}_Шаблон_отчёта.docx"
        if lab.id == "C3-S5-LR01" and target.exists():
            continue
        build_report(lab, target)
    after = hashlib.sha256(REFERENCE.read_bytes()).hexdigest().upper()
    if after != REFERENCE_SHA256:
        raise RuntimeError("Reference DOCX was modified")


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--content", action="store_true")
    parser.add_argument("--reports", action="store_true")
    args = parser.parse_args()
    if not args.content and not args.reports:
        args.content = args.reports = True
    if args.content:
        generate_content()
    if args.reports:
        generate_reports()
    print(json.dumps({"labs": len(LABS), "content": args.content, "reports": args.reports}, ensure_ascii=False))


if __name__ == "__main__":
    main()
