def points_for(lab: Lab) -> int:
    return POINTS[lab.id]


def format_points(value: float) -> str:
    return f"{value:g}".replace(".", ",")


def score_label(value: str) -> str:
    return f"{value} балл" if value == "1" else f"{value} балла"


def total_points_label(lab: Lab) -> str:
    points = points_for(lab)
    if points % 10 == 1 and points % 100 != 11:
        noun = "балл"
    elif 2 <= points % 10 <= 4 and not 12 <= points % 100 <= 14:
        noun = "балла"
    else:
        noun = "баллов"
    return f"{points} {noun}"


def rubric_scores(lab: Lab) -> tuple[str, str, str, str, str]:
    points = points_for(lab)
    if points == 10:
        values = (4.0, 2.0, 2.0, 1.0, 1.0)
    else:
        values = (points * 0.4, points * 0.2, points * 0.2, points * 0.1, points * 0.1)
    return tuple(format_points(value) for value in values)


def ensure(path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)


def write(path: Path, content: str) -> None:
    ensure(path)
    path.write_text(content.rstrip() + "\n", encoding="utf-8")


def bullets(items: Iterable[str]) -> str:
    return "\n".join(f"- {item}" for item in items)


def ordered(items: Iterable[str]) -> str:
    return "\n".join(f"{index}. {item}" for index, item in enumerate(items, 1))


def lecture_links(lab: Lab) -> str:
    return "\n".join(f"- [{title}]({url})" for title, url in lab.lectures)


